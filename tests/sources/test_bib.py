"""sync-bib's generator: the four allowed transformations, and nothing else.

Tests that call pandoc (via Quarto) or yamlfmt are skipped when those aren't installed.
"""

import json
import shutil
import subprocess
from pathlib import Path

import pytest
import yaml

from lib.sources import bib

needs_quarto = pytest.mark.skipif(shutil.which("quarto") is None, reason="quarto not installed")
needs_yamlfmt = pytest.mark.skipif(shutil.which("yamlfmt") is None, reason="yamlfmt not installed")
REPO_ROOT = Path(__file__).resolve().parents[2]


def item(key, csl, extra="", item_type="report", native_key=None):
    data = {"key": key, "itemType": item_type, "extra": extra, "citationKey": native_key or ""}
    return {"key": key, "data": data, "csljson": {"id": f"123/{key}", "type": "report"} | csl}


ITEMS = [
    item(
        "A1",
        {
            "title": "Docket 23-150: Order",
            "author": [{"family": "Massachusetts Department of Public Utilities", "given": ""}],
            "issued": {"date-parts": [[2024, 6, 24]]},
            "URL": "https://example.org/a---b_c_*x*?q=<1>",
            "note": "Citation Key: madpu_Docket23150Order_2024\ntex.shortauthor: MA DPU",
            "citation-key": "madpu_Docket23150Order_2024",
        },
        extra="Citation Key: madpu_Docket23150Order_2024\ntex.shortauthor: MA DPU",
    ),
    item(
        "B2",
        {
            "title": "Statement of Revenues *draft* <b>v2</b> --- final",
            "author": [{"family": "Public Service Electric and Gas Company", "given": ""}],
            "publisher": "Public Service Electric and Gas Company",
            "issued": {"date-parts": [[2023, 11, 31]]},
            "ISSN": "03062619",
            "note": "Citation Key: pseg_StatementRevenuesDraft_2023\n_eprint: 2410.04540",
        },
        extra="Citation Key: pseg_StatementRevenuesDraft_2023\n_eprint: 2410.04540",
    ),
    item("C3", {"title": "Unpinned item"}, native_key="x_UnpinnedItem_nd"),
    item("D4", {}, item_type="attachment"),
]


def test_transformations():
    result = bib.build_references(ITEMS)
    assert [r["id"] for r in result.records] == ["madpu_Docket23150Order_2024", "pseg_StatementRevenuesDraft_2023"]
    a, b = result.records
    assert a["author-short"] == "MA DPU"
    assert "note" not in a and "citation-key" not in a
    assert b["note"] == "_eprint: 2410.04540"
    assert b["publisher"] == "Public Service Electric and Gas Company"  # repeats the author: kept, fixed in Zotero
    assert result.unpinned == [{"zotero_item": "C3", "title": ""}]
    assert result.literal_dates == {"pseg_StatementRevenuesDraft_2023": {"issued": "2023-11-31"}}


def test_faithful_mirror_apart_from_allowed_changes():
    for it, rec in zip(ITEMS[:2], bib.build_references(ITEMS).records, strict=True):
        source = dict(it["csljson"])
        allowed = {"id", "note", "citation-key", "author-short"}
        assert {k: v for k, v in rec.items() if k not in allowed} == {
            k: v for k, v in source.items() if k not in allowed
        }


def test_order_does_not_depend_on_api_order():
    dup = [item(k, {"title": k}, extra="Citation Key: brattle_NewYorksGrid_2025a") for k in ("V2ITEM", "V1ITEM")]
    forward = [r["title"] for r in bib.build_references(dup).records]
    backward = [r["title"] for r in bib.build_references(dup[::-1]).records]
    assert forward == backward == ["V1ITEM", "V2ITEM"]


def test_include_unpinned_uses_native_key():
    result = bib.build_references(ITEMS, include_unpinned=True)
    assert "x_UnpinnedItem_nd" in [r["id"] for r in result.records]
    assert result.unpinned == []


def _write(tmp_path: Path) -> Path:
    path = tmp_path / "references.yaml"
    bib.write_references_yaml(bib.build_references(ITEMS), path, 42, REPO_ROOT)
    return path


def _render(tmp_path: Path, bibliography: Path, text: str) -> str:
    doc = tmp_path / "doc.md"
    doc.write_text(text, encoding="utf-8")
    out = subprocess.run(
        ["quarto", "pandoc", str(doc), "--citeproc", "--bibliography", str(bibliography), "-t", "plain", "--wrap=none"],
        capture_output=True,
        text=True,
        check=True,
    )
    return out.stdout


@needs_quarto
@needs_yamlfmt
def test_output_is_yamlfmt_stable_strict_yaml_and_deterministic(tmp_path):
    path = _write(tmp_path)
    text = path.read_text(encoding="utf-8")
    assert text.startswith("# Generated by just sync-bib from Zotero group library version 42. Do not edit.\n")
    assert bib.header_version(path) == 42
    copy = tmp_path / "copy.yaml"
    copy.write_text(text, encoding="utf-8")
    subprocess.run(["yamlfmt", str(copy)], cwd=REPO_ROOT, check=True)
    assert copy.read_text(encoding="utf-8") == text
    yaml.safe_load(text)  # strict parsers accept it: the invalid date is a quoted literal
    assert 'literal: "2023-11-31"' in text
    again = tmp_path / "again"
    again.mkdir()
    assert _write(again).read_text(encoding="utf-8") == text


@needs_quarto
@needs_yamlfmt
def test_values_survive_a_render_unchanged(tmp_path):
    path = _write(tmp_path)
    out = _render(tmp_path, path, "[@madpu_Docket23150Order_2024]\n\n[@pseg_StatementRevenuesDraft_2023]\n")
    assert "https://example.org/a---b_c_*x*?q=<1>" in out
    assert "Public Service Electric and Gas Company" in out
    assert "Public Service Electric; Gas" not in out
    assert "2023-11-31" in out
    assert "*draft*" in out.lower() and "--- final" in out.lower()  # Markdown in Zotero text stays literal


@needs_quarto
@needs_yamlfmt
def test_readback_equals_pandoc_normalized_source(tmp_path):
    """Read the YAML back through pandoc and compare with pandoc's reading of the CSL-JSON."""
    result = bib.build_references(ITEMS)
    src = tmp_path / "src.json"
    src.write_text(json.dumps(result.records), encoding="utf-8")
    base_path, back_path = tmp_path / "base.json", tmp_path / "back.json"
    subprocess.run(["quarto", "pandoc", "-f", "csljson", "-t", "csljson", str(src), "-o", str(base_path)], check=True)
    body = _write(tmp_path).read_text(encoding="utf-8").split("\n", 1)[1]
    doc = tmp_path / "meta.md"
    doc.write_text(f"---\n{body}---\n", encoding="utf-8")
    subprocess.run(["quarto", "pandoc", str(doc), "-s", "-t", "csljson", "-o", str(back_path)], check=True)
    base = {r["id"]: r for r in json.loads(base_path.read_text())}
    for rec in json.loads(back_path.read_text()):
        expected = base[rec["id"]]
        for var in ("title", "URL", "ISSN", "publisher", "author", "author-short", "note"):
            got, want = rec.get(var), expected.get(var)
            if var == "author":
                want = [{k: v for k, v in n.items() if v} for n in want or []] or None
            assert got == want, var


