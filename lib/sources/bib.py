"""Build ``reports/references.yaml`` from Zotero (``just sync-bib``).

The file is a faithful mirror of Zotero's own CSL-JSON export of each item in the Reports
collection. Its only transformations are:

1. ``id`` is the item's pinned citation key (``Citation Key:`` in Extra); the key lines
   (``Citation Key:``, ``tex.shortauthor:``) are removed from ``note``, and the duplicate
   ``citation-key`` variable is dropped.
2. ``author-short`` comes from ``tex.shortauthor:`` in Extra.
3. Items without a pinned key are excluded (reported as "not yet processed").
4. Serialization: pandoc's CSL-YAML writer (which applies the Markdown escaping pandoc
   needs to read the values back verbatim), lowercase variable names, records sorted by
   ``id``, a fixed key order, invalid dates written as ``literal``, and yamlfmt.

There is no data repair: if an entry looks wrong, fix the item in Zotero and rerun.
"""

from __future__ import annotations

import calendar
import copy
import json
import re
import shutil
import subprocess
import tempfile
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from lib.sources import extra

HEADER = "# Generated by just sync-bib from Zotero group library version {version}. Do not edit.\n"
HEADER_RE = re.compile(r"^# Generated by just sync-bib from Zotero group library version (\d+)\.")
DATE_VARIABLES = ("issued", "accessed", "original-date", "event-date", "submitted", "available-date")
QUOTED_VARIABLES = frozenset({"id", "url", "doi"})
YAMLFMT_HINT = "yamlfmt is required (see the yamlfmt hook in .pre-commit-config.yaml for install instructions)"


@dataclass
class BuildResult:
    """CSL records for the bibliography, plus what was left out or needs fixing in Zotero."""

    records: list[dict[str, Any]]
    unpinned: list[dict[str, str]] = field(default_factory=list)
    literal_dates: dict[str, dict[str, str]] = field(default_factory=dict)


def pinned_key(data: Mapping[str, Any]) -> str | None:
    """The item's pinned citation key from Extra, if any."""
    return extra.get(data.get("extra"), extra.CITATION_KEY)


def _invalid_date_text(date: Mapping[str, Any]) -> str | None:
    """ISO-like text for a CSL date whose parts are impossible (e.g. 2023-11-31), else None."""
    for parts in date.get("date-parts") or []:
        try:
            nums = [int(p) for p in parts]
        except (TypeError, ValueError):
            return "-".join(str(p) for p in parts)
        if len(nums) >= 2 and not 1 <= nums[1] <= 12:
            return "-".join(f"{n:02d}" if i else f"{n:04d}" for i, n in enumerate(nums))
        if len(nums) >= 3 and not 1 <= nums[2] <= calendar.monthrange(nums[0], nums[1])[1]:
            return "-".join(f"{n:02d}" if i else f"{n:04d}" for i, n in enumerate(nums))
    return None


def build_record(item: Mapping[str, Any], key: str) -> tuple[dict[str, Any], dict[str, str]]:
    """One CSL record from a Zotero API item (``data`` + ``csljson``), and its invalid dates."""
    data, csl = item["data"], copy.deepcopy(item["csljson"])
    csl["id"] = key
    csl.pop("citation-key", None)
    note = extra.remove_fields(csl.get("note"), (extra.CITATION_KEY, extra.SHORTAUTHOR))
    if note:
        csl["note"] = note
    else:
        csl.pop("note", None)
    if short := extra.get(data.get("extra"), extra.SHORTAUTHOR):
        csl["author-short"] = short
    literal_dates = {
        var: text for var in DATE_VARIABLES if isinstance(csl.get(var), dict) and (text := _invalid_date_text(csl[var]))
    }
    return csl, literal_dates


def build_references(items: Iterable[Mapping[str, Any]], *, include_unpinned: bool = False) -> BuildResult:
    """CSL records for every bibliographic item with a pinned key, sorted by ``id``.

    ``include_unpinned`` falls back to Zotero's native ``citationKey`` field for items with
    no pinned key. It exists only to compare against the pre-cleanup bibliography.
    """
    result = BuildResult(records=[])
    for item in sorted(items, key=lambda it: it["key"]):
        data = item["data"]
        if data["itemType"] in ("attachment", "note", "annotation"):
            continue
        key = pinned_key(data) or (data.get("citationKey") if include_unpinned else None)
        if not key:
            result.unpinned.append({"zotero_item": item["key"], "title": data.get("title", "")})
            continue
        record, literal_dates = build_record(item, key)
        result.records.append(record)
        if literal_dates:
            result.literal_dates[key] = literal_dates
    result.records.sort(key=lambda r: r["id"])  # stable: duplicate ids stay in Zotero item-key order
    return result


# --- serialization -------------------------------------------------------------------------


class _Loader(yaml.BaseLoader):
    """Reads every scalar as a string, so pandoc's escaped text passes through untouched."""


class _Dumper(yaml.SafeDumper):
    """Plain scalars where safe, double quotes otherwise; never reformats values."""

    def choose_scalar_style(self):
        style = super().choose_scalar_style()
        return '"' if style == "'" else style


# Quote only what a YAML 1.1 reader would turn into a non-string (bools, nulls); numbers and
# dates stay plain, as pandoc reads every bibliography value as text.
_Dumper.yaml_implicit_resolvers = {
    ch: [(tag, rx) for tag, rx in resolvers if tag in ("tag:yaml.org,2002:bool", "tag:yaml.org,2002:null")]
    for ch, resolvers in yaml.SafeDumper.yaml_implicit_resolvers.items()
}


_NUMBER_RE = re.compile(r"^[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?$")


def _changes_as_number(value: str) -> bool:
    """Whether a YAML reader would turn ``value`` into a number that prints differently ("0306")."""
    if not _NUMBER_RE.match(value):
        return False
    try:
        return str(int(value)) != value
    except ValueError:
        return repr(float(value)) != value


def _represent_str(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style='"' if _changes_as_number(value) else None)


class _Quoted(str):
    pass


_Dumper.add_representer(str, _represent_str)
_Dumper.add_representer(_Quoted, lambda d, v: d.represent_scalar("tag:yaml.org,2002:str", str(v), style='"'))


def pandoc_csl_yaml(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Records as pandoc's CSL-YAML writer emits them (Markdown-escaped strings)."""
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "refs.json"
        dst = Path(tmp) / "refs.md"
        src.write_text(json.dumps(records, ensure_ascii=False), encoding="utf-8")
        # Write to a file: `quarto pandoc` drops chunks of long stdout output.
        subprocess.run(
            ["quarto", "pandoc", "-f", "csljson", "-t", "markdown", "-s", "--wrap=none", str(src), "-o", str(dst)],
            capture_output=True,
            check=True,
        )
        out = dst.read_text(encoding="utf-8")
    # The document body is empty, so the output is exactly one metadata block.
    out = out.rstrip()
    if not (out.startswith("---\n") and out.endswith("\n---")):
        raise RuntimeError("unexpected pandoc output: expected a single YAML metadata block")
    meta = out.removeprefix("---\n").removesuffix("\n---")
    return yaml.load(meta, Loader=_Loader).get("references") or []


def _normalize(value: Any, var: str | None = None) -> Any:
    if isinstance(value, dict):
        items = sorted(((str(k).lower(), v) for k, v in value.items()), key=lambda kv: kv[0])
        return {k: _normalize(v, k) for k, v in items}
    if isinstance(value, list):
        return [_normalize(v) for v in value]
    return _Quoted(value) if var in QUOTED_VARIABLES else value


def _unescape_id(escaped: str) -> str:
    return re.sub(r"\\(.)", r"\1", escaped)


def to_yaml(result: BuildResult, library_version: int) -> str:
    """Serialize records as the body of ``references.yaml`` (before yamlfmt)."""
    pandoc_records = pandoc_csl_yaml(result.records)
    if len(pandoc_records) != len(result.records):
        raise RuntimeError(f"pandoc returned {len(pandoc_records)} records for {len(result.records)}")
    out = []
    for source, rec in zip(result.records, pandoc_records, strict=True):
        if _unescape_id(rec["id"]) != source["id"]:
            raise RuntimeError(f"pandoc reordered or altered ids: {rec['id']!r} vs {source['id']!r}")
        rec = _normalize(rec)
        # pandoc reads ids from a bibliography file without unescaping, so the id is raw.
        rec["id"] = _Quoted(source["id"])
        for var, text in result.literal_dates.get(source["id"], {}).items():
            rec[var] = {"literal": _Quoted(text)}
        out.append(rec)
    out.sort(key=lambda r: r["id"])
    body = yaml.dump(
        {"references": out},
        Dumper=_Dumper,
        sort_keys=False,
        allow_unicode=True,
        width=1_000_000,
        default_flow_style=False,
    )
    return HEADER.format(version=library_version) + body


def yamlfmt(path: Path, repo_root: Path) -> None:
    """Format ``path`` with the repo's yamlfmt (same binary and config as pre-commit)."""
    if not shutil.which("yamlfmt"):
        raise RuntimeError(YAMLFMT_HINT)
    subprocess.run(["yamlfmt", str(path)], cwd=repo_root, check=True)


def write_references_yaml(result: BuildResult, path: Path, library_version: int, repo_root: Path) -> None:
    """Write and yamlfmt the bibliography atomically."""
    tmp = path.with_suffix(".yaml.tmp")
    tmp.write_text(to_yaml(result, library_version), encoding="utf-8")
    yamlfmt(tmp, repo_root)
    tmp.replace(path)


def header_version(path: Path) -> int | None:
    """Library version recorded in an existing file's header, if any."""
    if not path.exists():
        return None
    with path.open(encoding="utf-8") as f:
        m = HEADER_RE.match(f.readline())
    return int(m.group(1)) if m else None
